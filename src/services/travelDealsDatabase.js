/**
 * Unified Multi-Country Getter
 */
export function getTravelDealsByCountry(country = "IN", category = "all", dealType = "all") {
  const normCountry = (country || "IN").toUpperCase();
  let dataset = TRAVEL_DEALS_INDIA;

  if (normCountry === "US") dataset = TRAVEL_DEALS_US;
  else if (normCountry === "GB" || normCountry === "UK") dataset = TRAVEL_DEALS_UK;
  else if (normCountry === "CA") dataset = TRAVEL_DEALS_CA;
  else if (normCountry === "AU") dataset = TRAVEL_DEALS_AU;
  else if (normCountry === "AE") dataset = TRAVEL_DEALS_AE;

  return dataset.filter((deal) => {
    const matchesCategory = category === "all" || deal.category === category;
    const matchesType = dealType === "all" || deal.dealType === dealType;
    return matchesCategory && matchesType;
  });
}
